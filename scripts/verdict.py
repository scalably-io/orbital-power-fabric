p(f"\n**Transmitter alone (weightless PV, duty 1), current tier: {tx_only:.0f} kg/kW per launch** "
  f"({tx_only * launches(L, sc.SAT_LIFE_LEO):.0f} over {L:.0f} y vs A {a_lo:.0f}) → B-LEO cannot beat A at today's measured "
  f"transmitter specific power (28 W/kg RF-out, R2-043) whatever the solar array weighs.")
need_tx = flip_value(lambda w: 1000 * sc.PUE * (0.90 * t.dc_rf / w) / t.post_pv * launches(L, sc.SAT_LIFE_LEO) - a_lo, 1.0, 1e5)
p(f"Break-even transmitter specific power (weightless PV, duty 1, current chain): **{need_tx:.0f} W/kg RF-out** ({need_tx/28:.1f}× today).")
